/** Летопись в виде, удобном для отрисовки: эпохи со своими главами. */
export function loreForDisplay(
  eras: { id: string }[],
  chapters: { id: string; era: string }[],
): LoreEra[] {
  return eras.map(era => {
    const text = ERA_TEXT[era.id]
    return {
      id: era.id,
      title: text?.title ?? era.id,
      period: text?.period ?? '',
      summary: text?.summary ?? '',
      chapters: chapters
        .filter(chapter => chapter.era === era.id)
        .map(chapter => {
          const body = CHAPTER_TEXT[chapter.id]
          return {
            id: chapter.id,
            title: body?.title ?? chapter.id,
            unlock: { kind: 'always' as const },
            paragraphs: body?.paragraphs ?? [],
          }
        }),
    }
  })
}
